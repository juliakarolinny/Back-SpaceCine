public class Avaliao {
    private String usuarios;
    private String estrelas;
    private String   reseCritica;
    private String dtAvaliacao;

    public String getUsuarios() {
        return usuarios;
    }

    public void setUsuarios(String usuarios) {
        this.usuarios = usuarios;
    }

    public String getEstrelas() {
        return estrelas;
    }

    public void setEstrelas(String estrelas) {
        this.estrelas = estrelas;
    }

    public String getReseCritica() {
        return reseCritica;
    }

    public void setReseCritica(String reseCritica) {
        this.reseCritica = reseCritica;
    }

    public String getDtAvaliacao() {
        return dtAvaliacao;
    }

    public void setDtAvaliacao(String dtAvaliacao) {
        this.dtAvaliacao = dtAvaliacao;
    }
}