public class Combo {
    public String tipos_de_combos;
    public String brindes;
    public Double valor;

    public String getTipos_de_combos() {
        return tipos_de_combos;
    }

    public void setTipos_de_combos(String tipos_de_combos) {
        this.tipos_de_combos = tipos_de_combos;
    }

    public String getBrindes() {
        return brindes;
    }

    public void setBrindes(String brindes) {
        this.brindes = brindes;
    }

    public Double getValor() {
        return valor;
    }

    public void setValor(Double valor) {
        this.valor = valor;
    }
}