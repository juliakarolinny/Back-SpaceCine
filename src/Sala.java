public class Sala {
private String informacoesSala;
private Integer assentos;
private String tiposSala;
private Integer idSala;

    public String getInformacoesSala() {
        return informacoesSala;
    }

    public void setInformacoesSala(String informacoesSala) {
        this.informacoesSala = informacoesSala;
    }

    public Integer getAssentos() {
        return assentos;
    }

    public void setAssentos(Integer assentos) {
        this.assentos = assentos;
    }

    public String getTiposSala() {
        return tiposSala;
    }

    public void setTiposSala(String tiposSala) {
        this.tiposSala = tiposSala;
    }

    public Integer getIdSala() {
        return idSala;
    }

    public void setIdSala(Integer idSala) {
        this.idSala = idSala;
    }
}